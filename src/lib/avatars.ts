const BY_ID = new Map(AVATAR_PRESETS.map((p) => [p.id, p]));

export function getAvatarPreset(photoPath: string | null | undefined): AvatarPreset | null {
  if (!photoPath) return null;
  return BY_ID.get(photoPath) ?? null;
}

export function isValidAvatarId(id: string | null | undefined): boolean {
  return Boolean(id && BY_ID.has(id));
}

export function presetSvgDataUrl(p: AvatarPreset): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 120">
    <defs>
      <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
        <stop offset="0%" stop-color="${p.c1}"/>
        <stop offset="100%" stop-color="${p.c2}"/>
      </linearGradient>
    </defs>
    <circle cx="60" cy="60" r="60" fill="url(#g)"/>
    <circle cx="60" cy="60" r="54" fill="none" stroke="rgba(255,255,255,0.25)" stroke-width="2"/>
    <text x="60" y="56" text-anchor="middle" dominant-baseline="central" font-size="44">${p.emoji}</text>
    <rect x="24" y="84" width="72" height="22" rx="11" fill="rgba(0,0,0,0.48)"/>
    <text x="60" y="96" text-anchor="middle" dominant-baseline="central" font-family="system-ui,sans-serif" font-size="11" font-weight="800" fill="#ffffff" letter-spacing="0.8">${p.badge}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

/**
 * Returns the portrait photo URL for a badminton legend, an inline SVG badge
 * for totems, or falls back to legacy Supabase Storage URL.
 */
export function avatarPublicUrl(photoPath: string): string {
  const preset = getAvatarPreset(photoPath);
  if (preset) return preset.photoUrl ?? presetSvgDataUrl(preset);
  return `${process.env.NEXT_PUBLIC_SUPABASE_URL}/storage/v1/object/public/avatars/${photoPath}`;
}
